import {
  S3Client,
  GetObjectCommand,
  DeleteObjectCommand,
  CopyObjectCommand,
  PutObjectCommand,
} from '@aws-sdk/client-s3';
import { createHash } from 'node:crypto';
import { getSignedUrl } from '@aws-sdk/s3-request-presigner';
import { env } from '@/lib/env';

const OBJECT_STORAGE_PUBLIC_BASE_URL = env.OBJECT_STORAGE_ENDPOINT_EXTERNAL.replace(/\/+$/, '');
const OBJECT_STORAGE_REGION = env.OBJECT_STORAGE_REGION;
const OBJECT_STORAGE_ADDRESSING_STYLE = env.OBJECT_STORAGE_ADDRESSING_STYLE;

const s3Client = new S3Client({
  endpoint: OBJECT_STORAGE_PUBLIC_BASE_URL,
  region: OBJECT_STORAGE_REGION,
  credentials: {
    accessKeyId: env.OBJECT_STORAGE_ACCESS_KEY,
    secretAccessKey: env.OBJECT_STORAGE_SECRET_KEY,
  },
  forcePathStyle: OBJECT_STORAGE_ADDRESSING_STYLE === 'path',
});

const BUCKET_NAME = env.OBJECT_STORAGE_BUCKET;
const QUIZ_PDF_OBJECT_ROOT = 'uploads/quiz_extract';
const PREMIUM_ASSET_OBJECT_ROOT = 'premium/assets';
const PREMIUM_SOURCE_OBJECT_ROOT = 'uploads/premium_sources';
const MAX_PREMIUM_ASSET_BYTES = 10 * 1024 * 1024;

/**
 * Return the only object-storage namespace a user-owned quiz PDF may occupy.
 * User ids are generated by the auth/database boundary, but keep the segment
 * validation here so a malformed id can never widen the cleanup prefix.
 */
export function getQuizPdfObjectPrefix(userId: string): string {
  if (typeof userId !== 'string' || !/^[a-zA-Z0-9_-]+$/.test(userId)) {
    throw new Error('Invalid quiz PDF owner id');
  }

  return `${QUIZ_PDF_OBJECT_ROOT}/${userId}/`;
}

/**
 * Get a signed URL for accessing a PDF
 * @param key - The S3 object key
 * @param expiresIn - URL expiry time in seconds (default: 1 hour)
 * @returns Signed URL for the PDF
 */
export async function getSignedPDFUrl(key: string, expiresIn: number = 3600): Promise<string> {
  const command = new GetObjectCommand({
    Bucket: BUCKET_NAME,
    Key: key,
    ResponseContentDisposition: 'inline',
    ResponseContentType: 'application/pdf',
  });

  return getSignedUrl(s3Client, command, { expiresIn });
}

/**
 * Extract an object key owned by this app's bucket from a stored URL.
 * Returns null when the URL does not reference this bucket or the key is unsafe.
 * Query/hash suffixes from signed URLs are stripped.
 */
function extractOwnedObjectKeyFromUrl(url: string): string | null {
  if (typeof url !== 'string' || url.length === 0) return null;

  let parsed: URL;
  try {
    parsed = new URL(url);
  } catch {
    return null;
  }

  const rawPath = url.match(/^[a-z][a-z\d+\-.]*:\/\/[^/]*(\/[^?#]*)?/i)?.[1] ?? '';
  for (const segment of rawPath.split('/')) {
    try {
      const decodedSegment = decodeURIComponent(segment);
      if (decodedSegment === '.' || decodedSegment === '..') return null;
    } catch {
      return null;
    }
  }

  const endpoint = new URL(OBJECT_STORAGE_PUBLIC_BASE_URL);
  const endpointHost = endpoint.hostname.toLowerCase();
  const host = parsed.hostname.toLowerCase();
  const isPathStyle = host === endpointHost && parsed.pathname.startsWith(`/${BUCKET_NAME}/`);
  const isVirtualHostedStyle =
    host === `${BUCKET_NAME.toLowerCase()}.${endpointHost}` && parsed.pathname.startsWith('/');
  if (!isPathStyle && !isVirtualHostedStyle) return null;

  const rawKey = isPathStyle
    ? parsed.pathname.slice(`/${BUCKET_NAME}/`.length)
    : parsed.pathname.slice(1);
  const key = rawKey.split(/[?#]/, 1)[0] ?? '';
  if (key.length === 0) return null;
  if (key.startsWith('/') || key.includes('\\') || key.includes('\0')) return null;
  if (
    key.split('/').some((segment) => segment.length === 0 || segment === '.' || segment === '..')
  ) {
    return null;
  }

  return key;
}

function premiumAssetKey(quizId: string, sourceIdentity: string, contentType?: string): string {
  if (!/^[a-f0-9]{24}$/i.test(quizId)) throw new Error('Invalid Premium quiz id');
  const extension =
    contentType === 'image/png'
      ? '.png'
      : contentType === 'image/webp'
        ? '.webp'
        : contentType === 'image/gif'
          ? '.gif'
          : contentType === 'image/svg+xml'
            ? '.svg'
            : '.jpg';
  const digest = createHash('sha256').update(sourceIdentity).digest('hex');
  return `${PREMIUM_ASSET_OBJECT_ROOT}/${quizId}/${digest}${extension}`;
}

/** Copy an allowlisted quiz image into the platform-owned private Premium namespace. */
export async function copyPremiumAssetToPrivateStorage(
  sourceUrl: string,
  quizId: string,
): Promise<string> {
  const ownedKey = extractOwnedObjectKeyFromUrl(sourceUrl);
  if (ownedKey) {
    const destination = premiumAssetKey(quizId, ownedKey);
    await s3Client.send(
      new CopyObjectCommand({
        Bucket: BUCKET_NAME,
        Key: destination,
        CopySource: encodeURIComponent(`${BUCKET_NAME}/${ownedKey}`),
      }),
    );
    return destination;
  }

  let parsed: URL;
  try {
    parsed = new URL(sourceUrl);
  } catch {
    throw new Error('Premium quiz image URL is invalid');
  }
  if (parsed.protocol !== 'https:' || parsed.hostname.toLowerCase() !== 'i.ibb.co') {
    throw new Error('Premium quiz images must come from managed image storage');
  }

  const response = await fetch(parsed, { redirect: 'error', cache: 'no-store' });
  if (!response.ok) throw new Error('Premium quiz image could not be copied');
  const contentType = response.headers.get('content-type')?.split(';', 1)[0]?.trim().toLowerCase();
  if (!contentType?.startsWith('image/')) throw new Error('Premium quiz asset is not an image');
  const declaredLength = Number(response.headers.get('content-length') ?? '0');
  if (declaredLength > MAX_PREMIUM_ASSET_BYTES) throw new Error('Premium quiz image is too large');
  const body = new Uint8Array(await response.arrayBuffer());
  if (body.byteLength === 0 || body.byteLength > MAX_PREMIUM_ASSET_BYTES) {
    throw new Error('Premium quiz image is empty or too large');
  }
  const destination = premiumAssetKey(quizId, sourceUrl, contentType);
  await s3Client.send(
    new PutObjectCommand({
      Bucket: BUCKET_NAME,
      Key: destination,
      Body: body,
      ContentType: contentType,
      CacheControl: 'private, no-store, max-age=0',
    }),
  );
  return destination;
}

/** Create a short-lived read URL only for objects in the private Premium namespace. */
export async function getSignedPremiumAssetUrl(key: string, expiresIn = 300): Promise<string> {
  if (
    !key.startsWith(`${PREMIUM_ASSET_OBJECT_ROOT}/`) ||
    key.includes('..') ||
    key.includes('\\')
  ) {
    throw new Error('Invalid Premium asset key');
  }
  return getSignedUrl(
    s3Client,
    new GetObjectCommand({
      Bucket: BUCKET_NAME,
      Key: key,
      ResponseCacheControl: 'private, no-store, max-age=0',
    }),
    { expiresIn },
  );
}

/** Create a short-lived admin URL for a retained Premium source PDF. */
export async function getSignedPremiumSourceUrl(key: string, expiresIn = 300): Promise<string> {
  if (
    !key.startsWith(`${PREMIUM_SOURCE_OBJECT_ROOT}/`) ||
    key.includes('..') ||
    key.includes('\\')
  ) {
    throw new Error('Invalid Premium source key');
  }
  return getSignedUrl(
    s3Client,
    new GetObjectCommand({
      Bucket: BUCKET_NAME,
      Key: key,
      ResponseContentDisposition: 'inline',
      ResponseContentType: 'application/pdf',
      ResponseCacheControl: 'private, no-store, max-age=0',
    }),
    { expiresIn },
  );
}

/**
 * Delete an object from object storage.
 * S3 DeleteObject is idempotent for missing keys (no error when the object is gone).
 */
async function deletePDF(key: string): Promise<void> {
  const command = new DeleteObjectCommand({
    Bucket: BUCKET_NAME,
    Key: key,
  });

  await s3Client.send(command);
}

/**
 * Best-effort cleanup of owned PDF/object URLs after an authoritative Mongo commit.
 * Never throws: external storage failures must not reverse committed DB deletes.
 * Non-owned / non-bucket URLs are skipped.
 */
export async function deleteOwnedPdfUrlsBestEffort(
  urls: readonly (string | null | undefined)[],
  requiredPrefix: string,
): Promise<void> {
  if (
    typeof requiredPrefix !== 'string' ||
    requiredPrefix.length === 0 ||
    !requiredPrefix.endsWith('/') ||
    requiredPrefix.startsWith('/') ||
    requiredPrefix.includes('\\') ||
    requiredPrefix.includes('\0') ||
    requiredPrefix
      .slice(0, -1)
      .split('/')
      .some((segment) => segment.length === 0 || segment === '.' || segment === '..')
  ) {
    return;
  }

  const keys = new Set<string>();
  for (const url of urls) {
    if (typeof url !== 'string') continue;
    const key = extractOwnedObjectKeyFromUrl(url);
    if (key?.startsWith(requiredPrefix)) keys.add(key);
  }

  await Promise.all(
    [...keys].map(async (key) => {
      try {
        await deletePDF(key);
      } catch {
        // Intentionally swallow: Mongo remains the source of truth after commit.
      }
    }),
  );
}

